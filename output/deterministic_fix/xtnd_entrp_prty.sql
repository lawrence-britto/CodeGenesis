SELECT
'RBC~VN~C_PRTY~XTND_ENTRP_PRTY~1' AS PROCESS_ID,
PRTY.DATA_SRC AS DATA_SRC,
PRTY.SOURCE_COUNTRY_CODE AS SOURCE_COUNTRY_CODE,
CPI.PRTY_SROGT_ID AS S_ENTRP_PRTY,
PRTY.DOM_PRTY_REF AS N_ENTRP_PRTY,
PRTY.DOM_PRTY AS N_CORE_PRTY,
PRTY.ACCS_SEGMT_CD AS ACCS_SEGMT_CD,
PRTY.ACCS_CTRY_CD AS ACCS_CTRY_CD,
EC_ACCT_EPR.TO_BALA_LCY AS A_TO_LCY,
EC_ACCT_EPR.CASA_BALA_SCY AS A_CASA_SCY,
UPPER(CPI.ID_REF) AS N_CUST
FROM (SELECT ACCS_CTRY_CD, ACCS_SEGMT_CD, DATA_SRC, DOM_PRTY, DOM_PRTY_REF, PRTY_SROGT_ID, SOURCE_COUNTRY_CODE FROM C_PRTY
    WHERE DATA_SRC = 'EBB'
   AND SOURCE_COUNTRY_CODE = 'VN'
) PRTY

LEFT JOIN (
    SELECT PRTY_SROGT_ID, ID_REF
    FROM C_PRTY_ID
    WHERE DATA_SRC = 'EBB'
   AND SOURCE_COUNTRY_CODE = 'VN'
   AND ID_TP_CD = 'N01'
) CPI
    ON PRTY.PRTY_SROGT_ID = CPI.PRTY_SROGT_ID

LEFT JOIN (SELECT CASA_BALA_SCY, ENTRP_PRTY_SROGT_ID, TO_BALA_LCY FROM E_CORE_ACCT_EPRTY_ROLLUP
    WHERE DATA_SRC = 'EBB'
   AND SOURCE_COUNTRY_CODE = 'VN'
) EC_ACCT_EPR
    ON TRIM(PRTY.PRTY_SROGT_ID) = TRIM(EC_ACCT_EPR.ENTRP_PRTY_SROGT_ID);